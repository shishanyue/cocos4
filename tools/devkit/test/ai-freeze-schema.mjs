    sha256: createHash('sha256').update(text).digest('hex'),
    schemaObjectSha256: createHash('sha256').update(JSON.stringify(schema)).digest('hex'),
    upstream: `https://github.com/anomalyco/opencode/tree/v${version}`, sources,
