// Maintainer research only. Never imported or invoked by the launcher or tests.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const devkit = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2);
assert.equal(args.length, 3, 'Use --research --out ABSENT_ABSOLUTE_TS_FILE; requires explicit maintainer network access.');
assert.equal(args[0], '--research');
assert.equal(args[1], '--out');
assert.ok(path.isAbsolute(args[2]));
const version = '1.18.21';
const url = 'https://opencode.ai/config.json';
const response = await fetch(url, { signal: AbortSignal.timeout(60000) });
assert.ok(response.ok, `Schema HTTP ${response.status}`);
const text = await response.text();
assert.ok(Buffer.byteLength(text) < 256 * 1024);
const schema = JSON.parse(text);
assert.equal(schema.$schema, 'https://json-schema.org/draft/2020-12/schema');
assert.equal(schema.$ref, '#/$defs/Config');
assert.equal(schema.$defs.Config.additionalProperties, false);
assert.equal(schema.$defs.McpLocalConfig.properties.command.type, 'array');
assert.equal(schema.$defs.Config.properties.skills.properties.paths.type, 'array');
const sources = [
    'packages/opencode/src/config/config.ts', 'packages/opencode/src/config/paths.ts',
    'packages/opencode/src/config/managed.ts', 'packages/core/src/global.ts',
    'packages/core/src/flag/flag.ts', 'packages/opencode/src/effect/runtime-flags.ts',
    'packages/core/src/npm.ts', 'packages/opencode/src/skill/index.ts',
    'packages/opencode/src/agent/agent.ts', 'packages/opencode/src/cli/cmd/mcp.ts',
    'packages/opencode/src/tool/read.ts', 'packages/opencode/src/tool/edit.ts',
    'packages/opencode/src/tool/write.ts', 'packages/opencode/src/tool/external-directory.ts',
    'packages/opencode/src/tool/apply_patch.ts', 'packages/opencode/src/tool/registry.ts',
    'packages/opencode/src/cli/cmd/debug/agent.handler.ts', 'packages/opencode/src/plugin/index.ts',
    'packages/opencode/src/session/instruction.ts',
    'packages/opencode/src/permission/index.ts', 'packages/opencode/src/project/project.ts', 'packages/core/src/project.ts',
];
